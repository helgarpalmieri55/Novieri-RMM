"""IT documentation module tables (docs/modules/documentation/spec.md §4).

Articles and typed records are soft-archived (history and audit survive);
every mutation snapshots into doc_versions. Links attach articles to core
entities — credential links reference metadata only, never secrets.
"""

from datetime import datetime
from typing import Any
from uuid import UUID

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    ForeignKey,
    Index,
    String,
    Text,
    UniqueConstraint,
    false,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, TimestampMixin, uuid7_pk


class DocArticle(TimestampMixin, Base):
    __tablename__ = "doc_articles"
    __table_args__ = (
        Index("ix_doc_articles_org_category", "org_id", "category"),
        # DECLARED HERE BECAUSE IT ONCE WAS NOT, and the index spent a month
        # not existing as a result. 0007 created it in raw SQL and left the
        # metadata ignorant of it; 0008, autogenerated one migration later,
        # saw an index nothing declared and emitted a bare
        # `op.drop_index('ix_doc_articles_fts')` into its `upgrade()`. Article
        # search ran on a sequential scan from July until 0079 put it back.
        #
        # The declaration is the half that stops it happening again: an
        # expression index the metadata knows about produces a remove/add PAIR
        # in autogenerate rather than a bare remove, so applying the diff
        # recreates the index instead of deleting it. The expression must stay
        # character-for-character identical to 0079's and to the `to_tsvector`
        # in `service.py` -- Postgres uses an expression index only for a query
        # whose expression matches it.
        Index(
            "ix_doc_articles_fts",
            text("to_tsvector('english', title || ' ' || body)"),
            postgresql_using="gin",
        ),
    )

    id: Mapped[UUID] = uuid7_pk()
    org_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"))
    title: Mapped[str] = mapped_column(String(300))
    body: Mapped[str] = mapped_column(Text, default="")
    category: Mapped[str] = mapped_column(String(100), default="General")
    archived: Mapped[bool] = mapped_column(Boolean, default=False)
    # Readable by requesters in the portal (migration 0160). Off by default:
    # the library is an internal runbook store unless someone says otherwise.
    portal_visible: Mapped[bool] = mapped_column(Boolean, server_default=false(), default=False)
    current_version: Mapped[int] = mapped_column(default=1)
    created_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)
    updated_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)


class DocRecord(TimestampMixin, Base):
    __tablename__ = "doc_records"
    __table_args__ = (Index("ix_doc_records_org_type", "org_id", "record_type"),)

    id: Mapped[UUID] = uuid7_pk()
    org_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"))
    record_type: Mapped[str] = mapped_column(String(20))  # network|service|vendor|location
    name: Mapped[str] = mapped_column(String(300))
    fields: Mapped[dict[str, Any]] = mapped_column(default=dict)
    archived: Mapped[bool] = mapped_column(Boolean, default=False)
    current_version: Mapped[int] = mapped_column(default=1)
    created_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)
    updated_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)


class DocLink(Base):
    __tablename__ = "doc_links"
    __table_args__ = (UniqueConstraint("article_id", "target_type", "target_id"),)

    id: Mapped[UUID] = uuid7_pk()
    org_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"))
    article_id: Mapped[UUID] = mapped_column(ForeignKey("doc_articles.id", ondelete="CASCADE"))
    target_type: Mapped[str] = mapped_column(String(20))  # device|device_group|credential|record
    target_id: Mapped[UUID] = mapped_column()


class DocVersion(Base):
    __tablename__ = "doc_versions"
    __table_args__ = (
        CheckConstraint(
            "(article_id IS NULL) != (record_id IS NULL)", name="doc_versions_one_parent"
        ),
        Index("ix_doc_versions_article", "article_id", "version"),
        Index("ix_doc_versions_record", "record_id", "version"),
    )

    id: Mapped[UUID] = uuid7_pk()
    org_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"))
    article_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("doc_articles.id", ondelete="CASCADE"), default=None
    )
    record_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("doc_records.id", ondelete="CASCADE"), default=None
    )
    version: Mapped[int] = mapped_column()
    snapshot: Mapped[dict[str, Any]] = mapped_column(default=dict)
    changed_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)
    ts: Mapped[datetime] = mapped_column()


# --------------------------------------------------------------------------- #
# Stored documents -- files (docs/modules/documentation/spec-attachments.md §2).
#
# A SIBLING OF THE FOUR TABLES ABOVE, NOT A REPLACEMENT FOR ANY OF THEM. An
# article is its own content; a document is a NAME for content that lives in
# the object store. That difference is why these are separate tables with a
# separate link table over the identical target vocabulary (§0.7) rather than a
# nullable column bolted onto `doc_articles`.
# --------------------------------------------------------------------------- #


class DocDocument(TimestampMixin, Base):
    """A stored document: a title, a category, and zero or more file versions."""

    __tablename__ = "doc_documents"
    __table_args__ = (
        Index("ix_doc_documents_org_category", "org_id", "category"),
        # DECLARED HERE AS WELL AS IN THE MIGRATION, and that is not
        # belt-and-braces -- it is the fix for an accident this module has
        # already suffered once. 0007 created `ix_doc_articles_fts` in raw SQL
        # and never declared it on the model; 0008, autogenerated one migration
        # later, saw an index the metadata did not know about and emitted
        # `op.drop_index('ix_doc_articles_fts')` into its `upgrade()`. Article
        # FTS has been running on a sequential scan ever since, and nothing
        # went red. An expression index the metadata knows about produces a
        # remove/add PAIR in autogenerate instead of a bare remove, so the next
        # `alembic revision --autogenerate` cannot quietly delete this one.
        Index(
            "ix_doc_documents_fts",
            text("to_tsvector('english', title || ' ' || description || ' ' || category)"),
            postgresql_using="gin",
        ),
    )

    id: Mapped[UUID] = uuid7_pk()
    org_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"))
    title: Mapped[str] = mapped_column(String(300))
    description: Mapped[str] = mapped_column(Text, default="")
    category: Mapped[str] = mapped_column(String(100), default="General")
    archived: Mapped[bool] = mapped_column(Boolean, default=False)
    #: STARTS AT 0, not at 1, and that differs deliberately from
    #: `DocArticle.current_version`. A document exists before its first file
    #: does (§4.1 -- metadata and bytes cannot share a request without a
    #: multipart parser), and a zero is the honest way to say "no file yet".
    #: An article starts at 1 because an article IS its own content.
    current_version: Mapped[int] = mapped_column(default=0)
    created_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)
    updated_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)


class DocDocumentVersion(Base):
    """One immutable file. APPEND-ONLY: no route updates a row here except
    purge (§6.3), which sets `purged_at`/`purged_by` and clears `object_key`.

    Immutable-per-version is CHEAPER than overwrite here, not more expensive
    (§0.6): the object key already needs a unique trailing segment, so using
    the version id costs nothing -- while an overwrite is the one operation in
    this module that can destroy the only copy of a file on a mis-click.
    """

    __tablename__ = "doc_document_versions"
    __table_args__ = (
        UniqueConstraint("document_id", "version", name="uq_doc_document_versions_doc_version"),
        Index("ix_doc_document_versions_org_doc", "org_id", "document_id", "version"),
    )

    id: Mapped[UUID] = uuid7_pk()
    org_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"))
    document_id: Mapped[UUID] = mapped_column(
        ForeignKey("doc_documents.id", ondelete="CASCADE")
    )
    version: Mapped[int] = mapped_column()
    #: The `s3://bucket/key` ref, or `""` once purged. NEVER leaves the control
    #: plane: no response shape in §10 contains it, which is mechanism 2 of the
    #: four that replace the RLS an object store cannot have (§3.3, F1b).
    object_key: Mapped[str] = mapped_column(Text, default="")
    #: The sanitized DISPLAY name. It never reaches the object key -- every
    #: segment of that is server-derived (§3.1).
    filename: Mapped[str] = mapped_column(String(255))
    byte_size: Mapped[int] = mapped_column()
    #: Server-sniffed from the leading bytes (§4.3). The client cannot declare
    #: one; there is no field in which it could arrive.
    content_type: Mapped[str] = mapped_column(String(100))
    #: `pdf | image | markdown | text | none`. STORED rather than derived at
    #: read time so the console's render map keys off one server-controlled
    #: value instead of re-deriving a rendering decision from `content_type`
    #: on the client (§0.4 wall 3).
    viewer: Mapped[str] = mapped_column(String(16))
    sha256: Mapped[str] = mapped_column(String(64))
    uploaded_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)
    created_at: Mapped[datetime] = mapped_column()
    #: Set by purge. The row SURVIVES as a tombstone -- filename, size, sha256,
    #: uploader and timestamps remain -- because a destroyed file should leave
    #: a mark, and `/content` answers 410 Gone rather than 404 (§5.1).
    purged_at: Mapped[datetime | None] = mapped_column(default=None)
    purged_by: Mapped[UUID | None] = mapped_column(ForeignKey("users.id"), default=None)


class DocDocumentLink(Base):
    """A document's relationship to a core entity, over the IDENTICAL target
    vocabulary `doc_links` already uses and resolved through the identical
    dictionary (§0.7). A second, document-tuned vocabulary would be a
    permanent version of the trap `documentation/service.py` already carries a
    comment about: the resolver dict and the route's regex must move together
    or one side 404s while the other 422s.

    A `credential` target carries METADATA ONLY, never a secret -- exactly as
    an article link does. Nothing in this module reads the vault.
    """

    __tablename__ = "doc_document_links"
    __table_args__ = (
        UniqueConstraint(
            "document_id", "target_type", "target_id", name="uq_doc_document_links_target"
        ),
        # By TARGET, not by document: the device-detail tab asks "what
        # documents cover this machine", which is this index's order.
        Index("ix_doc_document_links_org_target", "org_id", "target_type", "target_id"),
    )

    id: Mapped[UUID] = uuid7_pk()
    org_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"))
    document_id: Mapped[UUID] = mapped_column(
        ForeignKey("doc_documents.id", ondelete="CASCADE")
    )
    target_type: Mapped[str] = mapped_column(String(20))
    target_id: Mapped[UUID] = mapped_column()
    created_at: Mapped[datetime] = mapped_column()
