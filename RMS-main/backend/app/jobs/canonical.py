"""Canonical JSON serialization.

Every signature and hash in the platform (job signing, audit chain) is computed
over this exact byte encoding: sorted keys, compact separators, UTF-8, no ASCII
escaping. Datetimes must be pre-formatted with rfc3339() — passing a datetime
raises so a formatting ambiguity can never silently change signed bytes.

DO NOT CHANGE `canonical_bytes`. It is a CROSS-LANGUAGE CONTRACT with no
versioning story.
------------------------------------------------------------------------------
The Go agent (`agent/internal/canonical`) reimplements this function
byte-for-byte and recomputes these bytes on the endpoint to verify the server's
Ed25519 job signature. A fleet is always mixed-version: agents in the field
were built against the bytes this function produced when they shipped and
update on their own schedule.

So a change here is not a refactor. Signatures computed by the new control
plane would be checked by deployed agents against bytes they compute the old
way, and the observable result is EVERY JOB IN THE FLEET REFUSED — with the
Python suite green (it signs and verifies with the same function) and the Go
suite green (it is pinned to a corpus generated before the change). Worse, the
obvious field fix is to relax verification on the endpoint, which retires
invariant #1 on the only machine where it matters.

The one place that goes red is `backend/tests/test_canonical_corpus.py`, which
compares this function's output against
`agent/internal/canonical/testdata/corpus.jsonl` (generated by
`scripts/export_canonical_corpus.py`). If you are here to change the encoding,
that break is the design question, not the test.
"""

import json
from collections.abc import Mapping
from datetime import UTC, datetime
from typing import Any


def _reject_unknown(obj: Any) -> Any:
    raise TypeError(  # i18n-exempt: serializer contract, unhandled 500
        f"not canonically serializable: {type(obj).__name__}"
    )


def canonical_bytes(obj: Mapping[str, Any]) -> bytes:
    return json.dumps(
        obj,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        default=_reject_unknown,
    ).encode("utf-8")


def rfc3339(dt: datetime) -> str:
    if dt.tzinfo is None:
        raise ValueError(  # i18n-exempt: serializer contract, unhandled 500
            "naive datetimes are ambiguous; pass an aware datetime"
        )
    return dt.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
