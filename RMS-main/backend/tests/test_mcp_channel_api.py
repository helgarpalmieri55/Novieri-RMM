def test_never_exposed_is_exactly_the_ten_routes_of_the_global_constraints() -> None:
    assert len(NEVER_EXPOSED) == 10
    assert set(NEVER_EXPOSED) == GLOBAL_CONSTRAINTS_NEVER_EXPOSED


def test_never_exposed_names_only_real_routes(api_env) -> None:
    real = {
        (method, path)
        for path, route in flatten(api_env.app.router)
        for method in (getattr(route, "methods", None) or ())
    }
    assert set(NEVER_EXPOSED) - real == set()
    assert len(api_env.app.state.mcp_never_route_ids) == len(NEVER_EXPOSED)


@pytest.mark.parametrize(("method", "path"), sorted(NEVER_EXPOSED))
async def test_every_never_exposed_route_refuses_the_channel(mcp_env, method, path) -> None:
    _, slug, sub = await _org_admin(mcp_env)
    async with marked_client(mcp_env) as client:
        resp = await client.request(
            method,
            _concrete(path),
            headers=_bearer(mcp_token(mcp_env, slug, sub), **{"Accept-Language": "es"}),
            json={},
        )
    assert resp.status_code == 403, resp.text
    assert resp.json()["detail"] == NEVER_ES


async def test_the_refusal_does_not_depend_on_authentication(mcp_env) -> None:
    # `POST /setup/claim` is unauthenticated by necessity; the refusal still holds
    # with no token at all, and in English without a language header.
    async with marked_client(mcp_env) as client:
        resp = await client.post("/api/v1/setup/claim", json={})
    assert resp.status_code == 403
    assert resp.json()["detail"] == NEVER_EN


async def test_the_same_path_with_another_method_is_not_refused(mcp_env) -> None:
    # `PUT /install-link` is never exposed; `GET /install-link` is an ordinary read.
    _, slug, sub = await _org_admin(mcp_env)
    async with marked_client(mcp_env) as client:
        resp = await client.get(
            "/api/v1/install-link", headers=_bearer(mcp_token(mcp_env, slug, sub))
        )
    assert resp.status_code == 200, resp.text


async def test_the_api_refuses_a_never_exposed_route_even_past_the_guard(mcp_env) -> None:
    # Defence in depth: with the outer guard's table emptied, `auth_context`'s
    # own route-identity check still refuses an authenticated never-exposed route.
    mcp_env.app.state.mcp_never_routes = ()
    _, slug, sub = await _org_admin(mcp_env)
    async with marked_client(mcp_env) as client:
        resp = await client.post(
            "/api/v1/enrollment-tokens", headers=_bearer(mcp_token(mcp_env, slug, sub)), json={}
        )
    assert resp.status_code == 403, resp.text
    assert resp.json()["detail"] == NEVER_EN


