async def test_a_token_with_both_audiences_is_refused_on_and_off_the_channel(
    mcp_env,
) -> None:
    # A token carrying BOTH audiences is still an MCP token: off the channel it
    # is refused, so an MCP grant can never be replayed against the console API.
    _, slug, sub = await _org_admin(mcp_env)
    token = mcp_env.idp.token(
        sub, slug, azp="claude", email=f"{sub}@test.local", extra={"aud": ["it-suite", MCP_AUD]}
    )
    resp = await mcp_env.client.get("/api/v1/me", headers=_bearer(token))
    assert resp.status_code == 401
    # ...and ON the channel it is refused too: 1c(a) admits only a token with the
    # MCP audience "and no other platform audience".
    async with marked_client(mcp_env) as client:
        resp = await client.get("/api/v1/me", headers=_bearer(token))
    assert resp.status_code == 401, resp.text
    assert resp.json()["detail"] == (
        "this token also grants the console and is not accepted over MCP"
    )


async def test_a_marked_portal_ticket_is_audited_as_via_mcp(mcp_env) -> None:
    # The portal resolves its principal through `auth_context` directly, never
    # `bound_auth_context`; the channel must still reach its audit writes.
    from app.models import TicketCategory, TicketQueue, User

    org_id = await mcp_env.create_org("mcp-portal")
    sub = await mcp_env.create_user(org_id, "requester")
    slug = await mcp_env.org_slug(org_id)
    async with AsyncSession(mcp_env.admin_engine, expire_on_commit=False) as session:
        async with session.begin():
            user_id = (
                await session.execute(select(User.id).where(User.external_subject == sub))
            ).scalar_one()
            queue = TicketQueue(org_id=org_id, key="q-mcp", name="Q", created_by=user_id)
            session.add(queue)
            await session.flush()
            category = TicketCategory(
                org_id=org_id,
                key="c-mcp",
                name="C",
                type="incident",
                default_queue_id=queue.id,
                created_by=user_id,
            )
            session.add(category)
            await session.flush()
            category_id = category.id

    async with marked_client(mcp_env) as client:
        resp = await client.post(
            "/api/v1/portal/tickets",
            headers=_bearer(mcp_token(mcp_env, slug, sub)),
            json={"category_id": str(category_id), "subject": "My printer is on fire"},
        )
    assert resp.status_code == 201, resp.text
    events = await _audit(mcp_env.admin_engine, org_id, "ticket.created")
    assert len(events) == 1
    assert events[0].meta["via"] == "mcp"
    assert events[0].meta["mcp_app"] == "claude"


def test_the_app_refuses_to_start_if_a_never_exposed_route_is_missing(
    api_env, monkeypatch
) -> None:
    # A renamed route must fail loudly at boot, not silently drop out of the guard.
    import app.mcp.exclusions as exclusions
    import app.mcp.guard as guard
    from app.main import create_app

    widened = exclusions.NEVER_EXPOSED | {("POST", "/api/v1/no-such-route")}
    monkeypatch.setattr(exclusions, "NEVER_EXPOSED", widened)
    monkeypatch.setattr(guard, "NEVER_EXPOSED", widened)
    with pytest.raises(RuntimeError, match="no-such-route"):
        create_app(api_env.settings)


def test_a_method_less_route_is_in_the_dispatch_table_for_every_method() -> None:
    # A raw ASGI `Route` serves every method; left out of the table, it could win
    # dispatch while the guard believed the tool's own route would.
    from starlette.routing import Route, WebSocketRoute

    from app.mcp.guard import dispatch_table, dispatched_route

    class Raw:  # an ASGI app, not a function: Starlette gives it no methods
        async def __call__(self, scope: object, receive: object, send: object) -> None: ...

    raw = Raw()

    async def ws(websocket: object) -> None: ...

    flat = [
        ("/api/v1/things/export", Route("/api/v1/things/export", raw)),
        ("/api/v1/things/stream", WebSocketRoute("/api/v1/things/stream", ws)),
        ("/api/v1/things/{thing_id}", Route("/api/v1/things/{thing_id}", raw, methods=["GET"])),
    ]
    table = dispatch_table(flat)
    assert dispatched_route(table, "GET", "/api/v1/things/export") == "GET /api/v1/things/export"
    assert dispatched_route(table, "POST", "/api/v1/things/export") == "POST /api/v1/things/export"
    stream = dispatched_route(table, "GET", "/api/v1/things/stream")
    assert stream == "GET /api/v1/things/{thing_id}"
