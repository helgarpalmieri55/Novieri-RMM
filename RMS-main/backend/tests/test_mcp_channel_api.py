"""The API recognises the MCP channel (MCP server plan, Task 3).

What a request arriving through `/mcp` changes about the API, and what it must
not change about a request that did not:

- the token is validated against the MCP resource, never the console audience,
  and a console token is refused on the channel (and vice versa);
- ten routes refuse the channel outright, before authentication, whatever the
  caller holds -- "refused twice" means the API refuses even if a tool for one
  were ever generated by mistake;
- a route gated on a credential or license-key permission refuses the channel
  even for an org-admin who holds it;
- every audit event written during the call says it came over MCP, and from
  which app; an unmarked request's audit metadata is untouched.
"""

import re
from typing import Any
from uuid import UUID, uuid4

import pytest
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession

from app.core.router_inspect import flatten
from app.mcp.exclusions import NEVER_EXPOSED
from app.models import AuditEvent
from tests.mcp_support import MCP_AUD, marked_client, mcp_token

NEVER_EN = "this action is never available to an AI app"
NEVER_ES = "esta acción nunca está disponible para una aplicación de IA"

# Global Constraints, "Never exposed, refused twice" -- verbatim.
GLOBAL_CONSTRAINTS_NEVER_EXPOSED = {
    ("POST", "/api/v1/credentials/{credential_id}/checkout"),
    ("GET", "/api/v1/licenses/{license_id}/key"),
    ("POST", "/api/v1/enrollment-tokens"),
    ("PUT", "/api/v1/install-link"),
    ("POST", "/api/v1/install-link/regenerate"),
    ("POST", "/api/v1/agent/releases/{release_id}/install-command"),
    ("POST", "/api/v1/agent/releases/{release_id}/deployment-token"),
    ("POST", "/api/v1/backup/recovery-keys/{key_id}/challenge"),
    ("POST", "/api/v1/backup/recovery-keys/{key_id}/prove"),
    ("POST", "/api/v1/setup/claim"),
}


@pytest.fixture()
async def mcp_env(api_env):
    """`api_env` as a deployment with `ITS_PUBLIC_CONSOLE_URL` set, so the MCP
    resource is `https://itms.example.com/mcp`. `app.state.settings` is this
    same object, so the change is what every request reads."""
    api_env.settings.public_console_url = "https://itms.example.com"
    return api_env


async def _org_admin(env: Any) -> tuple[UUID, str, str]:
    org_id = await env.create_org("mcp")
    sub = await env.create_user(org_id, "org-admin")
    return org_id, await env.org_slug(org_id), sub


def _bearer(token: str, **extra: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}", **extra}


def _concrete(path: str) -> str:
    return re.sub(r"\{[^}]+\}", str(uuid4()), path)


async def _audit(engine: AsyncEngine, org_id: UUID, action: str) -> list[AuditEvent]:
    async with AsyncSession(engine) as session:
        return list(
            (
                await session.execute(
                    select(AuditEvent)
                    .where(AuditEvent.org_id == org_id, AuditEvent.action == action)
                    .order_by(AuditEvent.id)
                )
            ).scalars()
        )


