// Package canonical reproduces app/jobs/canonical.py::canonical_bytes exactly:
//
//	json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
//	    .encode("utf-8")
//
// Every job signature in the platform is Ed25519 over these bytes
// (app/jobs/engine.py::_payload, _sign; docs/03-security-model.md). The agent
// recomputes them from the frame it received and verifies the server's
// signature against the result, so a one-byte disagreement is not a formatting
// nit: it is every job in the fleet being REFUSED at the endpoint, with every
// test in this repository green — or somebody relaxing verification on the
// endpoint to make the symptom stop, which retires invariant #1 on the only
// machine where it matters.
//
// # Why this is hand-rolled
//
// encoding/json cannot produce these bytes. Measured against go1.24.7 by
// TestEncodingJSONIsNotASubstitute -- not asserted from memory:
//
//   - json.Marshal escapes '<', '>' and '&' as \u003c, \u003e, \u0026. Python
//     never escapes them. SetEscapeHTML(false) fixes this one.
//   - It escapes U+2028 and U+2029 unconditionally; Python with
//     ensure_ascii=False emits them raw. SetEscapeHTML(false) does NOT help,
//     which is what makes reaching for that option a near miss rather than a
//     fix.
//   - Decoding into `any` without UseNumber turns every number into a float64.
//     9007199254740993 comes back as ...992, -0.0 as -0, 1e-07 as 1e-7, and
//     123456789012345678901234567890 as 1.2345678901234568e+29.
//
// docs/modules/agent/plan.md C5 lists a fourth -- that Go emits \u0008 and
// \u000c where Python emits the short forms \b and \f. THAT IS NO LONGER
// TRUE: go1.24.7 emits the short forms. It was true of older toolchains, which
// is exactly the argument for not delegating: the standard encoder's escaping
// is a moving target, and "it agrees on this toolchain" is not a contract with
// a Python function. The corpus pins the agreements as well as the
// divergences, so either moving is a test failure rather than a field incident.
//
// So: no delegation to encoding/json for strings or numbers, and the result is
// pinned to testdata/corpus.jsonl, which is generated by calling the Python
// function (scripts/export_canonical_corpus.py), not by reasoning about it.
//
// # Why numbers are emitted verbatim
//
// A received number is a json.Number and is written out as its literal token.
// That is sound because the server produces the wire text and the canonical
// text from the same Python object with the same encoder — the gateway sends
// json.dumps(envelope) (app/gateway/dispatch.py:65, app/gateway/main.py:250)
// and signs canonical_bytes(payload), and json.dumps renders ints and floats
// with the same reprs in both places. Reformatting the token here would mean
// guessing at CPython's float repr, which agrees with the corpus and diverges
// on some customer's params. Bytes therefore REFUSES a Go native int or
// float64: the path is taken away rather than guessed at.
//
// (Python's json.dumps would emit bare NaN/Infinity for a non-finite float,
// which is not valid JSON. Such a frame is rejected by the decoder here before
// canonicalisation, which is the right way round: refusing a job is safe,
// executing one whose bytes we cannot reproduce is not.)
package canonical

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"slices"
	"unicode/utf8"
)

// ErrNativeNumber is returned when a Go int or float reaches the encoder. Only
// a json.Number — a token that arrived on the wire — can be canonicalised.
var ErrNativeNumber = errors.New(
	"canonical: native Go numbers cannot be canonicalised; decode with " +
		"json.Decoder.UseNumber so the received token is preserved verbatim",
)

// Bytes canonicalises an already-decoded value.
//
// Accepted: map[string]any, []any, string, json.Number, bool, nil — the shapes
// BytesFromRaw produces. Anything else is an error, mirroring
// canonical.py::_reject_unknown, which raises TypeError rather than improvising
// a representation for a value nobody signed.
func Bytes(v any) ([]byte, error) {
	var buf bytes.Buffer
	if err := write(&buf, v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// BytesFromRaw decodes a JSON document and canonicalises it. This is the entry
// point the signed-job verifier uses: it is handed the exact bytes of the
// envelope's `job` member, so an unknown field a newer control plane added is
// still inside the signed payload and still covered.
func BytesFromRaw(raw json.RawMessage) ([]byte, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	v, err := decode(dec, 0)
	if err != nil {
		return nil, err
	}
	// Trailing content means the frame is not the single document it claimed
	// to be, and which half was signed would be a guess.
	if _, err := dec.Token(); !errors.Is(err, io.EOF) {
		if err == nil {
			return nil, errors.New("canonical: trailing content after the JSON value")
		}
		return nil, fmt.Errorf("canonical: trailing content after the JSON value: %w", err)
	}
	return Bytes(v)
}

// MaxDepth bounds container nesting.
//
// Canonicalisation runs BEFORE signature verification — it has to, since the
// signature is over the canonical bytes — so this decoder is the first thing
// to touch a frame off the wire. Unbounded recursion there is a
// crash-the-agent primitive, and an agent that dies is an endpoint that stops
// answering jobs. The bound is far beyond any realistic job params; the point
// is that there IS one and that exceeding it refuses the frame rather than
// taking the process down.
const MaxDepth = 10000

// decode reads one value, token by token.
//
// json.Unmarshal into map[string]any would be shorter, but it silently keeps
// the LAST of a duplicated key. A frame with a duplicated key has no single
// signed meaning, and picking one is how a signature check becomes advisory —
// so this rejects it.
func decode(dec *json.Decoder, depth int) (any, error) {
	if depth > MaxDepth {
		return nil, fmt.Errorf("canonical: nesting deeper than %d", MaxDepth)
	}
	tok, err := dec.Token()
	if err != nil {
		return nil, fmt.Errorf("canonical: %w", err)
	}
	return decodeFrom(dec, tok, depth)
}

func decodeFrom(dec *json.Decoder, tok json.Token, depth int) (any, error) {
	switch t := tok.(type) {
	case json.Delim:
		switch t {
		case '{':
			obj := map[string]any{}
			for dec.More() {
				keyTok, err := dec.Token()
				if err != nil {
					return nil, fmt.Errorf("canonical: %w", err)
				}
				key, ok := keyTok.(string)
				if !ok {
					return nil, fmt.Errorf("canonical: object key is %T, not a string", keyTok)
				}
				if _, dup := obj[key]; dup {
					return nil, fmt.Errorf("canonical: duplicate object key %q: the signed "+
						"meaning of this frame is ambiguous", key)
				}
				val, err := decode(dec, depth+1)
				if err != nil {
					return nil, err
				}
				obj[key] = val
			}
			if _, err := dec.Token(); err != nil { // consume '}'
				return nil, fmt.Errorf("canonical: %w", err)
			}
			return obj, nil
		case '[':
			arr := []any{}
			for dec.More() {
				val, err := decode(dec, depth+1)
				if err != nil {
					return nil, err
				}
				arr = append(arr, val)
			}
			if _, err := dec.Token(); err != nil { // consume ']'
				return nil, fmt.Errorf("canonical: %w", err)
			}
			return arr, nil
		default:
			return nil, fmt.Errorf("canonical: unexpected delimiter %q", t)
		}
	case string, bool, json.Number, nil:
		return tok, nil
	default:
		// UseNumber is set, so a float64 here would mean the decoder changed
		// behaviour underneath us.
		return nil, fmt.Errorf("canonical: unexpected token type %T", tok)
	}
}

func write(buf *bytes.Buffer, v any) error {
	switch t := v.(type) {
	case nil:
		buf.WriteString("null")
		return nil
	case bool:
		if t {
			buf.WriteString("true")
		} else {
			buf.WriteString("false")
		}
		return nil
	case string:
		return writeString(buf, t)
	case json.Number:
		return writeNumber(buf, t)
	case map[string]any:
		// Python sorts object keys by code point; sorting Go strings sorts by
		// UTF-8 byte, and for valid UTF-8 the two orders are identical (UTF-8
		// is order-preserving by construction). The key_sort_order corpus case
		// is what proves it, rather than this comment.
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		slices.Sort(keys)
		buf.WriteByte('{')
		for i, k := range keys {
			if i > 0 {
				buf.WriteByte(',') // separators=(",", ":") — no spaces
			}
			if err := writeString(buf, k); err != nil {
				return err
			}
			buf.WriteByte(':')
			if err := write(buf, t[k]); err != nil {
				return err
			}
		}
		buf.WriteByte('}')
		return nil
	case []any:
		buf.WriteByte('[')
		for i, e := range t {
			if i > 0 {
				buf.WriteByte(',')
			}
			if err := write(buf, e); err != nil {
				return err
			}
		}
		buf.WriteByte(']')
		return nil
	case int, int8, int16, int32, int64,
		uint, uint8, uint16, uint32, uint64, float32, float64:
		return fmt.Errorf("%w (got %T)", ErrNativeNumber, v)
	default:
		// canonical.py::_reject_unknown raises TypeError here rather than
		// letting `default=` improvise a representation of something nobody
		// signed. Same rule.
		return fmt.Errorf("canonical: not canonically serializable: %T", v)
	}
}

func writeNumber(buf *bytes.Buffer, n json.Number) error {
	s := string(n)
	// The token is emitted verbatim, so it must be checked: an unvalidated
	// json.Number constructed by a caller could put arbitrary bytes into the
	// signed message. json.Valid alone would accept `"x"` and `null`, hence
	// the leading-byte check.
	if s == "" || (s[0] != '-' && (s[0] < '0' || s[0] > '9')) || !json.Valid([]byte(s)) {
		return fmt.Errorf("canonical: %q is not a JSON number token", s)
	}
	buf.WriteString(s)
	return nil
}

// hexDigits is lowercase: Python's json.encoder writes '\\u%04x'.
const hexDigits = "0123456789abcdef"

// writeString implements CPython's py_encode_basestring (ensure_ascii=False):
// escape only '"', '\\', and the C0 controls; use the short forms for
// \b \t \n \f \r; \u00xx with lowercase hex for the rest. NOTHING else is
// escaped — not '<', '>', '&', '/', U+007F, U+2028 or U+2029, and no non-ASCII
// codepoint.
func writeString(buf *bytes.Buffer, s string) error {
	if !utf8.ValidString(s) {
		// canonical_bytes ends in .encode("utf-8"), which raises rather than
		// substituting. Substituting here would produce bytes that verify
		// against nothing.
		return errors.New("canonical: string is not valid UTF-8")
	}
	buf.WriteByte('"')
	start := 0
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 0x20 && c != '"' && c != '\\' {
			continue // includes every byte of every multi-byte rune (>= 0x80)
		}
		if start < i {
			buf.WriteString(s[start:i])
		}
		switch c {
		case '"':
			buf.WriteString(`\"`)
		case '\\':
			buf.WriteString(`\\`)
		case '\b':
			buf.WriteString(`\b`)
		case '\f':
			buf.WriteString(`\f`)
		case '\n':
			buf.WriteString(`\n`)
		case '\r':
			buf.WriteString(`\r`)
		case '\t':
			buf.WriteString(`\t`)
		default:
			buf.WriteString(`\u00`)
			buf.WriteByte(hexDigits[c>>4])
			buf.WriteByte(hexDigits[c&0xf])
		}
		start = i + 1
	}
	if start < len(s) {
		buf.WriteString(s[start:])
	}
	buf.WriteByte('"')
	return nil
}
