"""documentation: put ix_doc_articles_fts back

`docs/modules/documentation/spec.md` §4.

THE INDEX HAS NOT EXISTED SINCE JULY. 0007 created it in raw SQL:

    CREATE INDEX ix_doc_articles_fts ON doc_articles
      USING gin(to_tsvector('english', title || ' ' || body))

and never declared it on `DocArticle`. 0008 was autogenerated one migration
later, compared the live database against model metadata that had never heard
of this index, and emitted a bare `op.drop_index('ix_doc_articles_fts')` into
its `upgrade()`. It is one line in an otherwise ordinary vault migration and it
reads as noise. Every database upgraded past 0008 lost the index, article
full-text search has been answering `to_tsvector(...) @@ plainto_tsquery(...)`
on a sequential scan for a month, and nothing went red -- no test asked whether
the index was there, and a sequential scan is slow rather than wrong.

WHY THIS IS A NEW MIGRATION AND NOT AN EDIT TO 0008. CLAUDE.md's carve-out for
editing a shipped migration needs all three of its conditions and this meets
none: the offending statement is in `upgrade()`, not `downgrade()`; that
`upgrade()` has demonstrably run in the field; and a forward migration CAN
express the fix, which is this file. Fewer than three means write a new one.

WHY IT IS ALSO DECLARED ON THE MODEL, in `app/models/documentation.py`. Putting
the index back without declaring it leaves the loaded gun exactly as it was:
the next `alembic revision --autogenerate` would see an unknown index and drop
it again. A declared expression index produces a remove/add PAIR instead of a
bare remove, because SQLAlchemy renders the expression differently from the way
Postgres reads it back -- noisy, but survivable, since applying the pair
recreates the index. 0075 uses that technique for `ix_doc_documents_fts` and
this follows it.

THE EXPRESSION IS 0007'S, CHARACTER FOR CHARACTER, because a differently
spelled index is not the same index: Postgres only uses an expression index for
a query whose expression matches it, so `title || ' ' || body` here and
`title || ' ' || body` in `service.py` have to stay the same string. Both
columns are NOT NULL (0007), so the concatenation cannot go NULL and index
nothing -- the failure mode 0075's header describes.

Revision ID: 0079
Revises: 0078
"""

from collections.abc import Sequence

from alembic import op

revision: str = "0079"
down_revision: str | None = "0078"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

_INDEX = "ix_doc_articles_fts"


def upgrade() -> None:
    # `IF NOT EXISTS` because this index is one a DBA may plausibly have put
    # back by hand after noticing the sequential scan, and an upgrade that dies
    # on a database that already has the right index would be a worse outcome
    # than a no-op.
    op.execute(
        f"CREATE INDEX IF NOT EXISTS {_INDEX} ON doc_articles "
        "USING gin(to_tsvector('english', title || ' ' || body))"
    )


def downgrade() -> None:
    op.execute(f"DROP INDEX IF EXISTS {_INDEX}")
