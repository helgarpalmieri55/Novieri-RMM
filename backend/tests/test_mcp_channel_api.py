async def test_a_token_with_both_audiences_is_refused_on_and_off_the_channel(
    mcp_env,
) -> None:
    # Off the channel no bearer is read at all, so an MCP grant can never be
    # replayed against the console API; ON the channel 1c(a) admits only a
    # token with the MCP audience "and no other platform audience".
    _, slug, sub = await _org_admin(mcp_env)
    claims = mcp_claims(await mcp_token(mcp_env, slug, sub))
    claims["aud"] = [MCP_BASE, f"{MCP_BASE}/mcp"]
    token = await signed_mcp_token(claims)
    resp = await mcp_env.client.get("/api/v1/me", headers=_bearer(token))
    assert resp.status_code == 401
    async with marked_client(mcp_env) as client:
        resp = await client.get("/api/v1/me", headers=_bearer(token))
    assert resp.status_code == 401, resp.text
    assert resp.json()["detail"] == "this access token was refused"


async def test_a_marked_portal_ticket_is_audited_as_via_mcp(mcp_env) -> None:
    # The portal resolves its principal through `auth_context` directly, never
    # `bound_auth_context`; the channel must still reach its audit writes.
    from app.models import TicketCategory, TicketQueue, User

    org_id = await mcp_env.create_org("mcp-portal")
    sub = await mcp_env.create_user(org_id, "requester")
    slug = await mcp_env.org_slug(org_id)
    async with AsyncSession(mcp_env.admin_engine, expire_on_commit=False) as session:
        async with session.begin():
            user_id = (
                await session.execute(select(User.id).where(User.external_subject == sub))
            ).scalar_one()
            queue = TicketQueue(org_id=org_id, key="q-mcp", name="Q", created_by=user_id)
            session.add(queue)
            await session.flush()
            category = TicketCategory(
                org_id=org_id,
                key="c-mcp",
                name="C",
                type="incident",
                default_queue_id=queue.id,
                created_by=user_id,
            )
            session.add(category)
            await session.flush()
            category_id = category.id

    async with marked_client(mcp_env) as client:
        resp = await client.post(
            "/api/v1/portal/tickets",
            headers=_bearer(await mcp_token(mcp_env, slug, sub)),
            json={"category_id": str(category_id), "subject": "My printer is on fire"},
        )
    assert resp.status_code == 201, resp.text
    events = await _audit(mcp_env.admin_engine, org_id, "ticket.created")
    assert len(events) == 1
    assert events[0].meta["via"] == "mcp"
    assert events[0].meta["mcp_app"] == "claude"


